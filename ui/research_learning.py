"""Read-only learning cards built exclusively from the customer projection.

Teaching text explains concepts; evidence rows preserve values and provenance.
No provider calls, financial forecasts, or investment authority live here.
"""
from __future__ import annotations

import math
from typing import Any, Mapping


EARNINGS_FIELDS = {
    "latest_revenue": ("Sales", "Revenue is money earned from customers before expenses. Sales alone do not tell you how much profit the company keeps."),
    "net_income": ("Profit", "Net income is profit after expenses and taxes. Accounting gains or one-time costs can affect it; compare the filing notes before calling a change lasting."),
    "operating_margin_pct": ("Profitability", "Operating margin is the share of sales left after running the business, before interest and taxes. Compare the same definition across matching periods."),
    "operating_cash_flow": ("Cash from operations", "Operating cash flow tracks cash generated by running the business. Timing of customer payments and bills can move it even when reported profit rises."),
    "free_cash_flow": ("Cash after investment", "Free cash flow generally means operating cash left after capital spending. Check the source definition; positive profit does not guarantee positive cash flow."),
    "forward_eps": ("Expected profit per share", "Forward EPS is an estimate of future profit per share, not a reported earnings result. It cannot establish that the company beat expectations."),
}


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _finite(value: Any) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)


def build_business_reader(page: Mapping[str, Any]) -> dict[str, Any]:
    """Connect the retained business description to reported money flows.

    Do not infer customers, segments, competitive advantages, or causality from
    an industry label or financial totals. Profile and financial facts retain
    independent provenance; a capture date is not a fiscal reporting period.
    """
    unavailable = {"status": "UNAVAILABLE", "description": None, "stages": ()}
    page = _mapping(page)
    if page.get("status") != "AVAILABLE":
        return unavailable
    about = _mapping(page.get("about"))
    profile = _mapping(about.get("profile"))
    provenance = _mapping(about.get("provenance"))
    def identity(value: Any) -> str | None:
        return value.strip() if isinstance(value, str) and value.strip() else None

    source = identity(provenance.get("source")) or identity(provenance.get("provider"))
    evidence_id = identity(provenance.get("raw_evidence_id"))
    description = next((profile[key].strip() for key in
                        ("description", "business_summary", "company_description")
                        if isinstance(profile.get(key), str) and profile[key].strip()), None)
    business = None
    if about.get("status") == "AVAILABLE" and description and source and evidence_id:
        business = dict(text=description, source=source, evidence_id=evidence_id,
                        as_of=provenance.get("capture_timestamp") or provenance.get("as_of"))
    snapshot = _mapping(page.get("financial_snapshot"))
    items = snapshot.get("items")
    if not isinstance(items, (tuple, list)):
        items = ()
    stages = []
    for field, title, question in (
        ("latest_revenue", "1. Money from customers", "What products or services do customers pay for?"),
        ("net_income", "2. Money kept as profit", "After expenses and taxes, did the company keep a profit or report a loss?"),
        ("operating_cash_flow", "3. Cash from running the business", "Did running the business bring in cash or use cash?"),
    ):
        candidates = [item for item in items
                      if isinstance(item, Mapping) and item.get("field") == field]
        # Conflicting duplicates must not be resolved by input ordering.
        item = candidates[0] if len(candidates) == 1 else {}
        fact = None
        if (snapshot.get("status") == "AVAILABLE" and _finite(item.get("value"))
                and item.get("unit") == "USD" and identity(item.get("provider"))
                and item.get("currency") in (None, "USD")
                and identity(item.get("evidence_id"))):
            fact = dict(item)
        stages.append(dict(field=field, title=title, question=question, fact=fact))
    return dict(status="AVAILABLE", description=business, stages=tuple(stages))


def build_valuation_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Explain admitted valuation evidence without deriving a multiple or target.

    Use individual fact provenance rather than the chart's shared timestamp:
    a retained close and a model estimate need not have the same evidence date.
    """
    facts = []
    models = []
    if page.get("status") == "AVAILABLE":
        for raw in page.get("fundamentals") or ():
            item = _mapping(raw)
            if (item.get("fact_name") in {"Last Certified Close", "ATLAS Fair Value"}
                    and item.get("classification") == "CERTIFIED_ATLAS"
                    and item.get("source") and item.get("evidence_ids")
                    and _finite(item.get("value"))):
                facts.append(dict(item))
        for raw in _mapping(page.get("financial_depth")).get("valuation_models") or ():
            item = _mapping(raw)
            if (_finite(item.get("value")) and item.get("unit") == "USD_PER_SHARE"
                    and item.get("source") == "CERTIFIED_ATLAS_VALUATION"):
                models.append({**dict(item), "assumptions": dict(_mapping(item.get("assumptions")))})
    return {"facts": tuple(facts), "models": tuple(models)}


def build_learning_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Select evidence without calculating trends or treating missing data as zero."""
    if page.get("status") != "AVAILABLE":
        return {"status": "UNAVAILABLE", "earnings": (), "headlines": ()}
    snapshot = _mapping(page.get("financial_snapshot"))
    rows = []
    seen = set()
    for item in snapshot.get("items") or ():
        if snapshot.get("status") != "AVAILABLE" or not isinstance(item, Mapping):
            continue
        field = item.get("field")
        value = item.get("value")
        if field not in EARNINGS_FIELDS or field in seen or not item.get("evidence_id"):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            continue
        seen.add(field)
        title, explanation = EARNINGS_FIELDS[field]
        rows.append({**dict(item), "question": title, "explanation": explanation})
    changes = _mapping(page.get("recent_changes"))
    headlines = tuple(dict(item) for item in changes.get("items") or ()
                      if isinstance(item, Mapping) and item.get("headline")
                      and item.get("article_publisher") and item.get("article_timestamp")) if changes.get("status") == "AVAILABLE" else ()
    summary = _mapping(page.get("summary"))
    conditions = _mapping(summary.get("watch_conditions"))
    return {
        "status": "AVAILABLE", "earnings": tuple(rows), "headlines": headlines,
        "bull_watch": tuple(conditions.get("strengthen") or ()),
        "bear_watch": tuple(conditions.get("weaken") or ()),
        "risks": tuple(summary.get("risks") or ()),
        "snapshot": _mapping(page.get("evidence")).get("evaluation_snapshot_id"),
    }


def build_news_reader(page: Mapping[str, Any]) -> dict[str, Any]:
    """Order admitted headlines against price evidence, never assessment time.

    Calendar dates span a whole UTC day; ambiguous ordering stays explicit.
    No clock, provider access, topic inference, or investment authority is used.
    """
    from datetime import date, datetime, time, timedelta, timezone

    def text(value: Any) -> str | None:
        return value.strip() if isinstance(value, str) and value.strip() else None

    def interval(value: Any):
        value = text(value)
        if not value:
            return None
        try:
            if len(value) == 10:
                start = datetime.combine(date.fromisoformat(value), time(), timezone.utc)
                return start, start + timedelta(days=1) - timedelta(microseconds=1)
            instant = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if instant.tzinfo is None:
                return None
            instant = instant.astimezone(timezone.utc)
            return instant, instant
        except (ValueError, OverflowError):
            return None

    unavailable = dict(status="UNAVAILABLE", reference=None, items=())
    page = _mapping(page)
    if page.get("status") != "AVAILABLE":
        return unavailable
    fundamentals = page.get("fundamentals")
    candidates = [item for item in fundamentals if isinstance(item, Mapping)
                  and item.get("fact_name") == "Last Certified Close"] if isinstance(fundamentals, (list, tuple)) else []
    reference = None
    if len(candidates) == 1:
        fact = candidates[0]
        ids = fact.get("evidence_ids")
        if (fact.get("classification") == "CERTIFIED_ATLAS" and text(fact.get("source"))
                and isinstance(ids, (list, tuple)) and ids
                and all(text(value) for value in ids) and interval(fact.get("source_timestamp"))):
            reference = dict(source=fact["source"], as_of=fact["source_timestamp"],
                             evidence_ids=tuple(ids))
    baseline = interval(reference["as_of"]) if reference else None
    changes = _mapping(page.get("recent_changes"))
    raw_items = changes.get("items")
    if changes.get("status") != "AVAILABLE" or not isinstance(raw_items, (list, tuple)):
        raw_items = ()
    rows = []
    seen = set()
    for raw in raw_items:
        item = _mapping(raw)
        headline, publisher = text(item.get("headline")), text(item.get("article_publisher"))
        if not headline or not publisher:
            continue
        published = interval(item.get("article_timestamp"))
        timestamp = item["article_timestamp"] if published else None
        identity = (headline, publisher, published)
        if identity in seen:
            continue
        seen.add(identity)
        relation = "UNAVAILABLE"
        if baseline and published:
            relation = ("AFTER" if published[0] > baseline[1] else
                        "BEFORE" if published[1] < baseline[0] else "OVERLAPPING")
        rows.append(dict(headline=headline, publisher=publisher, published_at=timestamp,
                         relation=relation, _order=published[0] if published else None))
    # Undated reports follow dated reports; input order breaks timestamp ties.
    rows.sort(key=lambda row: (row["_order"] is not None,
                              row["_order"] or datetime.min.replace(tzinfo=timezone.utc)), reverse=True)
    for row in rows:
        del row["_order"]
    return dict(status="AVAILABLE" if rows else "UNAVAILABLE", reference=reference, items=tuple(rows))


# Deliberately limited to reported annual series already admitted by the page.
ANNUAL_QUESTIONS = {
    "Revenue": ("USD", "Sales", "Did customer demand grow, or did prices or acquisitions lift sales? The figures alone cannot explain the cause."),
    "Net Income": ("USD", "Profit", "Did profit keep pace with sales? Check costs, taxes, and one-time gains or charges in the filing."),
    "Operating Cash Flow": ("USD", "Cash from operations", "Did cash follow profit? Customer payments, inventory, and bill timing can explain a difference."),
    "Free Cash Flow": ("USD", "Cash after investment", "How much cash remained after investment? Check the source definition and whether spending was deferred."),
    "Operating Margin": ("PERCENT", "Operating margin", "Did the company keep more of each sales dollar? Check pricing, costs, and changes in the business mix."),
}


def build_annual_earnings_comparison(page: Mapping[str, Any]) -> dict[str, Any]:
    """Compare adjacent full years, never infer reporting frequency or causes.

    This is arithmetic on retained evidence, not an earnings surprise, forecast,
    or change to a certified investment assessment. Fail closed on ambiguous
    dates, duplicate periods, unsupported units, and incomplete provenance.
    """
    from datetime import date

    unavailable = {"status": "UNAVAILABLE", "rows": ()}
    trend = _mapping(page.get("financial_trend"))
    provenance = _mapping(trend.get("provenance"))
    source = provenance.get("source") or provenance.get("provider")
    evidence_ids = provenance.get("evidence_ids") or ()
    if isinstance(evidence_ids, (tuple, list)):
        evidence_ids = tuple(str(value) for value in evidence_ids if value)
    else:
        evidence_ids = ()
    if not evidence_ids and provenance.get("raw_evidence_id"):
        evidence_ids = (str(provenance["raw_evidence_id"]),)
    if (page.get("status") != "AVAILABLE" or trend.get("status") != "AVAILABLE"
            or trend.get("periodicity") != "ANNUAL" or not source or not evidence_ids):
        return unavailable
    periods = trend.get("periods")
    if not isinstance(periods, (list, tuple)) or len(periods) < 2:
        return unavailable
    try:
        dates = [date.fromisoformat(value) for value in periods]
    except (TypeError, ValueError):
        return unavailable
    if len(set(dates)) != len(dates):
        return unavailable
    order = sorted(range(len(dates)), key=dates.__getitem__)
    earlier, latest = order[-2:]
    prior, current = dates[earlier], dates[latest]
    if current.year != prior.year + 1 or (current.month, current.day) != (prior.month, prior.day):
        return unavailable
    rows = []
    series = _mapping(trend.get("series"))
    units = _mapping(trend.get("units"))
    for label, (unit, title, question) in ANNUAL_QUESTIONS.items():
        values = series.get(label)
        if (units.get(label) != unit or not isinstance(values, (tuple, list))
                or len(values) != len(periods)):
            continue
        previous, value = values[earlier], values[latest]
        if not _finite(previous) or not _finite(value):
            continue
        change = value - previous
        if not _finite(change):
            continue
        rows.append(dict(label=title, prior=previous, current=value, change=change,
                         unit=unit, question=question))
    if not rows:
        return unavailable
    return dict(status="AVAILABLE", rows=tuple(rows), prior_period=periods[earlier],
                current_period=periods[latest], source=source, evidence_ids=evidence_ids,
                as_of=provenance.get("capture_timestamp") or provenance.get("as_of"))


def build_earnings_walkthrough(page: Mapping[str, Any]) -> dict[str, Any]:
    """Explain numerical relationships, never infer business causes or a rating.

    Reuse the annual comparison's admission rules and exact period pair. Each
    observation identifies its inputs so the UI can cite the evidence once and
    a reader can trace the explanation back to the displayed figures.
    """
    comparison = build_annual_earnings_comparison(page)
    if comparison["status"] != "AVAILABLE":
        return {"status": "UNAVAILABLE", "observations": ()}
    rows = {row["label"]: row for row in comparison["rows"]}
    observations = []

    def add(code: str, title: str, inputs: tuple[str, ...], reading: str, check: str) -> None:
        observations.append(dict(code=code, title=title, inputs=inputs, reading=reading, check=check))

    # Describe signs explicitly: a smaller loss must never be called profit
    # growth, and a positive change from zero has no meaningful growth rate.
    for label, positive, negative in (
        ("Profit", "profit", "a loss"),
        ("Cash after investment", "cash left after investment", "a cash shortfall after investment"),
    ):
        row = rows.get(label)
        if not row:
            continue
        prior, current = row["prior"], row["current"]
        if prior < 0 < current:
            reading = f"The earlier year showed {negative}; the later year showed {positive}. One positive year does not establish a lasting recovery."
            code = "turned_positive"
        elif current < 0 < prior:
            reading = f"The earlier year showed {positive}; the later year showed {negative}."
            code = "turned_negative"
        elif current < 0 and prior < 0:
            direction = "smaller" if current > prior else "larger" if current < prior else "unchanged"
            reading = f"Both years showed {negative}. The shortfall was {direction}; the later year was still below zero."
            code = "negative_both_years"
        elif current == 0:
            reading = f"The later reported value was zero. It showed neither {positive} nor {negative} at the retained precision."
            code = "at_zero"
        elif prior == 0:
            reading = f"The earlier reported value was zero; the later year showed {positive if current > 0 else negative}. A percentage growth rate from zero is undefined."
            code = "from_zero"
        else:
            direction = "higher" if current > prior else "lower" if current < prior else "unchanged"
            reading = f"Both years showed {positive}. The later value was {direction}."
            code = "positive_both_years"
        check = (
            "Check taxes, one-time gains or charges, and accounting changes before treating this as recurring earning power."
            if label == "Profit" else
            "Check the source definition and capital spending. Lower investment can leave more cash today while reducing capacity for the future."
        )
        add(f"{label}:{code}", f"What does {label.lower()} mean here?", (label,), reading, check)

    sales, margin = rows.get("Sales"), rows.get("Operating margin")
    if sales and margin and sales["prior"] > 0 and sales["current"] > 0:
        sales_direction = "rose" if sales["change"] > 0 else "fell" if sales["change"] < 0 else "were unchanged"
        margin_direction = "more" if margin["change"] > 0 else "less" if margin["change"] < 0 else "the same amount of"
        add("sales_and_margin", "Did sales translate into operating profit?", ("Sales", "Operating margin"),
            f"Sales {sales_direction}. The company reported {margin_direction} operating profit per sales dollar in the later year. A negative margin means an operating loss on each sales dollar.",
            "Check pricing, input costs, acquisitions, and the mix of products sold. These figures do not identify which factor caused the change.")

    profit, cash = rows.get("Profit"), rows.get("Cash from operations")
    if profit and cash:
        if profit["current"] > 0 and cash["current"] <= 0:
            reading = "The later year reported a profit, but operating cash was zero or negative. Reported profit did not come with positive cash from running the business that year."
        elif profit["current"] < 0 and cash["current"] > 0:
            reading = "The later year reported a loss while operations generated positive cash. Accounting profit and cash measure different things."
        elif profit["change"] > 0 and cash["change"] < 0:
            reading = "Reported profit moved higher while cash from operations moved lower. An improvement in the profit figure did not come with an improvement in operating cash."
        else:
            reading = "Profit and operating cash measure different things. Their levels and changes alone do not establish earnings quality."
        add("profit_and_cash", "Did reported profit come with cash?", ("Profit", "Cash from operations"), reading,
            "Reconcile profit to operating cash in the cash-flow statement. Check non-cash charges and changes in customer payments, inventory, and bills; the cause is unavailable here.")

    return {**comparison, "status": "AVAILABLE" if observations else "UNAVAILABLE",
            "observations": tuple(observations)}
