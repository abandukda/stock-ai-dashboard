"""Read-only learning cards built exclusively from the customer projection.

Teaching text explains concepts; evidence rows preserve values and provenance.
No provider calls, financial forecasts, or investment authority live here.
"""
from __future__ import annotations

import math
from typing import Any, Mapping


EARNINGS_FIELDS = {
    "latest_revenue": ("Sales", "Revenue is money earned from customers before expenses. Sales alone do not tell you how much profit the company keeps."),
    "net_income": ("Profit", "Net income is profit after expenses and taxes. Accounting gains or one-time costs can affect it; compare the filing notes before calling a change lasting."),
    "operating_margin_pct": ("Profitability", "Operating margin is the share of sales left after running the business, before interest and taxes. Compare the same definition across matching periods."),
    "operating_cash_flow": ("Cash from operations", "Operating cash flow tracks cash generated by running the business. Timing of customer payments and bills can move it even when reported profit rises."),
    "free_cash_flow": ("Cash after investment", "Free cash flow generally means operating cash left after capital spending. Check the source definition; positive profit does not guarantee positive cash flow."),
    "forward_eps": ("Expected profit per share", "Forward EPS is an estimate of future profit per share, not a reported earnings result. It cannot establish that the company beat expectations."),
}

VALUATION_METHODS = {
    "VAL_FORWARD_PE_V1": (
        "This approach values expected profit per share using a price-to-earnings multiple. "
        "The multiple is how much investors pay for each dollar of yearly profit. "
        "Both the profit estimate and the multiple can be too optimistic; forward profit is not a reported result."
    ),
    "VAL_FCFF_DCF_V1": (
        "A discounted cash-flow model estimates future cash available to the business and translates it into today's money. "
        "Cash expected far in the future is worth less today. Growth, the required return, and the value assigned "
        "to later years can have a large effect; debt and cash also matter when moving from business value to share value."
    ),
}


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _finite(value: Any) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)


def build_valuation_lesson(page: Mapping[str, Any]) -> dict[str, Any]:
    """Read published references only; never create a target or implied return.

    Missing lineage stays missing, even if a chart has a convenient date.
    Model assumptions are retained verbatim, without inferred units.
    """
    result: dict[str, Any] = {"status": "UNAVAILABLE", "references": (), "models": ()}
    if page.get("status") != "AVAILABLE":
        return result
    references = []
    evidence = _mapping(page.get("valuation_evidence"))
    for key, label in (("price", "Last certified close"), ("fair_value", "ATLAS Fair Value estimate")):
        item = _mapping(evidence.get(key))
        if _finite(item.get("value")):
            references.append({**dict(item), "label": label, "kind": key})
    models = []
    depth = _mapping(page.get("financial_depth"))
    if depth.get("status") in {"FULL", "LIMITED"}:
        for item in depth.get("valuation_models") or ():
            if not isinstance(item, Mapping) or not _finite(item.get("value")):
                continue
            if item.get("unit") != "USD_PER_SHARE":
                continue
            models.append({**dict(item), "assumptions": dict(_mapping(item.get("assumptions"))),
                           "explanation": VALUATION_METHODS.get(item.get("methodology_id"))})
    return {"status": "AVAILABLE", "references": tuple(references), "models": tuple(models)}


def build_learning_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Select evidence without calculating trends or treating missing data as zero."""
    if page.get("status") != "AVAILABLE":
        return {"status": "UNAVAILABLE", "earnings": (), "headlines": ()}
    snapshot = _mapping(page.get("financial_snapshot"))
    rows = []
    seen = set()
    for item in snapshot.get("items") or ():
        if snapshot.get("status") != "AVAILABLE" or not isinstance(item, Mapping):
            continue
        field = item.get("field")
        value = item.get("value")
        if field not in EARNINGS_FIELDS or field in seen or not item.get("evidence_id"):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            continue
        seen.add(field)
        title, explanation = EARNINGS_FIELDS[field]
        rows.append({**dict(item), "question": title, "explanation": explanation})
    changes = _mapping(page.get("recent_changes"))
    headlines = tuple(dict(item) for item in changes.get("items") or ()
                      if isinstance(item, Mapping) and item.get("headline")
                      and item.get("article_publisher") and item.get("article_timestamp")) if changes.get("status") == "AVAILABLE" else ()
    summary = _mapping(page.get("summary"))
    conditions = _mapping(summary.get("watch_conditions"))
    return {
        "status": "AVAILABLE", "earnings": tuple(rows), "headlines": headlines,
        "bull_watch": tuple(conditions.get("strengthen") or ()),
        "bear_watch": tuple(conditions.get("weaken") or ()),
        "risks": tuple(summary.get("risks") or ()),
        "snapshot": _mapping(page.get("evidence")).get("evaluation_snapshot_id"),
    }
