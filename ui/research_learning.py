"""Read-only learning cards built exclusively from the customer projection.

Teaching text explains concepts; evidence rows preserve values and provenance.
No provider calls, financial forecasts, or investment authority live here.
"""
from __future__ import annotations

import math
from typing import Any, Mapping


EARNINGS_FIELDS = {
    "latest_revenue": ("Sales", "Revenue is money earned from customers before expenses. Sales alone do not tell you how much profit the company keeps."),
    "net_income": ("Profit", "Net income is profit after expenses and taxes. Accounting gains or one-time costs can affect it; compare the filing notes before calling a change lasting."),
    "operating_margin_pct": ("Profitability", "Operating margin is the share of sales left after running the business, before interest and taxes. Compare the same definition across matching periods."),
    "operating_cash_flow": ("Cash from operations", "Operating cash flow tracks cash generated by running the business. Timing of customer payments and bills can move it even when reported profit rises."),
    "free_cash_flow": ("Cash after investment", "Free cash flow generally means operating cash left after capital spending. Check the source definition; positive profit does not guarantee positive cash flow."),
    "forward_eps": ("Expected profit per share", "Forward EPS is an estimate of future profit per share, not a reported earnings result. It cannot establish that the company beat expectations."),
}


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _finite(value: Any) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)


def build_valuation_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Explain admitted valuation evidence without deriving a multiple or target.

    Use individual fact provenance rather than the chart's shared timestamp:
    a retained close and a model estimate need not have the same evidence date.
    """
    facts = []
    models = []
    if page.get("status") == "AVAILABLE":
        for raw in page.get("fundamentals") or ():
            item = _mapping(raw)
            if (item.get("fact_name") in {"Last Certified Close", "ATLAS Fair Value"}
                    and item.get("classification") == "CERTIFIED_ATLAS"
                    and item.get("source") and item.get("evidence_ids")
                    and _finite(item.get("value"))):
                facts.append(dict(item))
        for raw in _mapping(page.get("financial_depth")).get("valuation_models") or ():
            item = _mapping(raw)
            if (_finite(item.get("value")) and item.get("unit") == "USD_PER_SHARE"
                    and item.get("source") == "CERTIFIED_ATLAS_VALUATION"):
                models.append({**dict(item), "assumptions": dict(_mapping(item.get("assumptions")))})
    return {"facts": tuple(facts), "models": tuple(models)}


def build_learning_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Select evidence without calculating trends or treating missing data as zero."""
    if page.get("status") != "AVAILABLE":
        return {"status": "UNAVAILABLE", "earnings": (), "headlines": ()}
    snapshot = _mapping(page.get("financial_snapshot"))
    rows = []
    seen = set()
    for item in snapshot.get("items") or ():
        if snapshot.get("status") != "AVAILABLE" or not isinstance(item, Mapping):
            continue
        field = item.get("field")
        value = item.get("value")
        if field not in EARNINGS_FIELDS or field in seen or not item.get("evidence_id"):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            continue
        seen.add(field)
        title, explanation = EARNINGS_FIELDS[field]
        rows.append({**dict(item), "question": title, "explanation": explanation})
    changes = _mapping(page.get("recent_changes"))
    headlines = tuple(dict(item) for item in changes.get("items") or ()
                      if isinstance(item, Mapping) and item.get("headline")
                      and item.get("article_publisher") and item.get("article_timestamp")) if changes.get("status") == "AVAILABLE" else ()
    summary = _mapping(page.get("summary"))
    conditions = _mapping(summary.get("watch_conditions"))
    return {
        "status": "AVAILABLE", "earnings": tuple(rows), "headlines": headlines,
        "bull_watch": tuple(conditions.get("strengthen") or ()),
        "bear_watch": tuple(conditions.get("weaken") or ()),
        "risks": tuple(summary.get("risks") or ()),
        "snapshot": _mapping(page.get("evidence")).get("evaluation_snapshot_id"),
    }


# Deliberately limited to reported annual series already admitted by the page.
ANNUAL_QUESTIONS = {
    "Revenue": ("USD", "Sales", "Did customer demand grow, or did prices or acquisitions lift sales? The figures alone cannot explain the cause."),
    "Net Income": ("USD", "Profit", "Did profit keep pace with sales? Check costs, taxes, and one-time gains or charges in the filing."),
    "Operating Cash Flow": ("USD", "Cash from operations", "Did cash follow profit? Customer payments, inventory, and bill timing can explain a difference."),
    "Free Cash Flow": ("USD", "Cash after investment", "How much cash remained after investment? Check the source definition and whether spending was deferred."),
    "Operating Margin": ("PERCENT", "Operating margin", "Did the company keep more of each sales dollar? Check pricing, costs, and changes in the business mix."),
}


def build_annual_earnings_comparison(page: Mapping[str, Any]) -> dict[str, Any]:
    """Compare adjacent full years, never infer reporting frequency or causes.

    This is arithmetic on retained evidence, not an earnings surprise, forecast,
    or change to a certified investment assessment. Fail closed on ambiguous
    dates, duplicate periods, unsupported units, and incomplete provenance.
    """
    from datetime import date

    unavailable = {"status": "UNAVAILABLE", "rows": ()}
    trend = _mapping(page.get("financial_trend"))
    provenance = _mapping(trend.get("provenance"))
    source = provenance.get("source") or provenance.get("provider")
    evidence_ids = provenance.get("evidence_ids") or ()
    if isinstance(evidence_ids, (tuple, list)):
        evidence_ids = tuple(str(value) for value in evidence_ids if value)
    else:
        evidence_ids = ()
    if not evidence_ids and provenance.get("raw_evidence_id"):
        evidence_ids = (str(provenance["raw_evidence_id"]),)
    if (page.get("status") != "AVAILABLE" or trend.get("status") != "AVAILABLE"
            or trend.get("periodicity") != "ANNUAL" or not source or not evidence_ids):
        return unavailable
    periods = trend.get("periods")
    if not isinstance(periods, (list, tuple)) or len(periods) < 2:
        return unavailable
    try:
        dates = [date.fromisoformat(value) for value in periods]
    except (TypeError, ValueError):
        return unavailable
    if len(set(dates)) != len(dates):
        return unavailable
    order = sorted(range(len(dates)), key=dates.__getitem__)
    earlier, latest = order[-2:]
    prior, current = dates[earlier], dates[latest]
    if current.year != prior.year + 1 or (current.month, current.day) != (prior.month, prior.day):
        return unavailable
    rows = []
    series = _mapping(trend.get("series"))
    units = _mapping(trend.get("units"))
    for label, (unit, title, question) in ANNUAL_QUESTIONS.items():
        values = series.get(label)
        if (units.get(label) != unit or not isinstance(values, (tuple, list))
                or len(values) != len(periods)):
            continue
        previous, value = values[earlier], values[latest]
        if not _finite(previous) or not _finite(value):
            continue
        change = value - previous
        if not _finite(change):
            continue
        rows.append(dict(label=title, prior=previous, current=value, change=change,
                         unit=unit, question=question))
    if not rows:
        return unavailable
    return dict(status="AVAILABLE", rows=tuple(rows), prior_period=periods[earlier],
                current_period=periods[latest], source=source, evidence_ids=evidence_ids,
                as_of=provenance.get("capture_timestamp") or provenance.get("as_of"))


def build_earnings_readout(page: Mapping[str, Any]) -> dict[str, Any]:
    """Teach relationships in the admitted annual pair without inferring causes.

    Every observation uses the same dated comparison. No forward estimates,
    snapshot facts, news, or model outputs may fill a missing annual series.
    Percentage growth is meaningful here only with a positive starting value.
    """
    comparison = build_annual_earnings_comparison(page)
    if comparison["status"] != "AVAILABLE":
        return {"status": "UNAVAILABLE", "cards": ()}
    rows = {row["label"]: row for row in comparison["rows"]}
    cards = []

    def add(title, labels, observation, meaning, check):
        missing = tuple(label for label in labels if label not in rows)
        cards.append(dict(title=title, status="UNAVAILABLE" if missing else "AVAILABLE",
                          missing=missing, observation=None if missing else observation,
                          meaning=meaning, check=check, inputs=tuple(labels)))

    sales, profit = rows.get("Sales"), rows.get("Profit")
    observation = None
    if sales and profit:
        def direction(row):
            return "rose" if row["change"] > 0 else "fell" if row["change"] < 0 else "did not change"

        observation = f'Sales {direction(sales)}; profit {direction(profit)}.'
        if profit["current"] < 0:
            observation += " The latest full year still recorded a loss."
        elif profit["current"] == 0:
            observation += " The latest full year recorded zero net income."
        elif profit["prior"] <= 0:
            observation += " The latest full year was profitable after a prior loss or break-even result."
        # Do not describe loss reduction as earnings growth or divide by zero.
        for label, row in (("Sales", sales), ("Profit", profit)):
            if row["prior"] > 0 and row["current"] >= 0:
                growth = row["change"] / row["prior"] * 100
                if _finite(growth):
                    observation += f" {label} changed {growth:+.1f}% from the earlier year."
    add("Did sales translate into profit?", ("Sales", "Profit"), observation,
        "Sales measure customer spending with the company; profit is what remains after expenses and taxes. Their directions can differ.",
        "Check pricing, costs, acquisitions, taxes, and one-time items in the filings before explaining the difference.")

    cash = rows.get("Cash from operations")
    observation = None
    if cash and profit:
        relation = "above" if cash["current"] > profit["current"] else "below" if cash["current"] < profit["current"] else "equal to"
        observation = f"Cash from operations was {relation} reported profit in the latest full year."
        if cash["current"] < 0:
            observation += " Operations used cash overall."
        elif cash["current"] == 0:
            observation += " Operations generated no net cash."
        else:
            observation += " Operations generated positive net cash."
    add("Did reported profit come with cash?", ("Profit", "Cash from operations"), observation,
        "Profit and operating cash measure different things. Cash above profit does not by itself prove high earnings quality; cash below profit does not prove accounting trouble.",
        "Check customer payments, inventory, supplier bills, and non-cash expenses. The figures here do not identify the cause.")

    free_cash = rows.get("Cash after investment")
    observation = None
    if free_cash:
        value = free_cash["current"]
        observation = ("Reported free cash flow was positive in the latest full year." if value > 0 else
                       "Reported free cash flow was negative in the latest full year." if value < 0 else
                       "Reported free cash flow was zero in the latest full year.")
        observation += (" It increased from the earlier year." if free_cash["change"] > 0 else
                        " It decreased from the earlier year." if free_cash["change"] < 0 else
                        " It was unchanged from the earlier year.")
    add("Was cash left after investment?", ("Cash after investment",), observation,
        "Free cash flow generally measures operating cash after capital spending. It is not a promise of dividends or cash available after every obligation.",
        "Check the source definition, spending timing, debt repayments, and whether investment was delayed. Negative free cash flow alone does not establish financial distress.")
    return {**comparison, "cards": tuple(cards)}
