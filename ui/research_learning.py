"""Read-only learning cards built exclusively from the customer projection.

Teaching text explains concepts; evidence rows preserve values and provenance.
No provider calls, financial forecasts, or investment authority live here.
"""
from __future__ import annotations

import math
from typing import Any, Mapping


EARNINGS_FIELDS = {
    "latest_revenue": ("Sales", "Revenue is money earned from customers before expenses. Sales alone do not tell you how much profit the company keeps."),
    "net_income": ("Profit", "Net income is profit after expenses and taxes. Accounting gains or one-time costs can affect it; compare the filing notes before calling a change lasting."),
    "operating_margin_pct": ("Profitability", "Operating margin is the share of sales left after running the business, before interest and taxes. Compare the same definition across matching periods."),
    "operating_cash_flow": ("Cash from operations", "Operating cash flow tracks cash generated by running the business. Timing of customer payments and bills can move it even when reported profit rises."),
    "free_cash_flow": ("Cash after investment", "Free cash flow generally means operating cash left after capital spending. Check the source definition; positive profit does not guarantee positive cash flow."),
    "forward_eps": ("Expected profit per share", "Forward EPS is an estimate of future profit per share, not a reported earnings result. It cannot establish that the company beat expectations."),
}


def _mapping(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _finite(value: Any) -> bool:
    return not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)


def build_evidence_workbook(page: Mapping[str, Any]) -> dict[str, Any]:
    """Copy admitted business context and aligned history, never infer a trend.

    Missing observations remain missing. No sorting, period relabeling, growth
    calculations or cross-source joins are safe with this contract.
    """
    result = {"business": None, "history": (), "periodicity": "UNAVAILABLE",
              "provenance": {}, "missing": ()}
    if page.get("status") != "AVAILABLE":
        return result
    about = _mapping(page.get("about"))
    profile = _mapping(about.get("profile"))
    provenance = _mapping(about.get("provenance"))
    if about.get("status") == "AVAILABLE" and provenance.get("raw_evidence_id"):
        description = next((profile[key].strip() for key in
                            ("description", "business_summary", "company_description")
                            if isinstance(profile.get(key), str) and profile[key].strip()), None)
        if description:
            result["business"] = {"description": description, "provenance": dict(provenance)}
    trend = _mapping(page.get("financial_trend"))
    provenance = _mapping(trend.get("provenance"))
    periods = trend.get("periods")
    series = _mapping(trend.get("series"))
    units = _mapping(trend.get("units"))
    definitions = {"Revenue": "USD", "Net Income": "USD", "Operating Cash Flow": "USD",
                   "Free Cash Flow": "USD", "EPS": "USD_PER_SHARE", "Operating Margin": "PERCENT"}
    admitted = {}
    if (trend.get("status") == "AVAILABLE"
            and (provenance.get("raw_evidence_id") or provenance.get("evidence_ids"))
            and isinstance(periods, (list, tuple)) and len(periods) >= 2
            and all(isinstance(period, str) and period.strip() for period in periods)
            and len(set(periods)) == len(periods)):
        for label, unit in definitions.items():
            values = series.get(label)
            if (units.get(label) == unit and isinstance(values, (list, tuple))
                    and len(values) == len(periods) and any(_finite(value) for value in values)):
                admitted[label] = tuple(value if _finite(value) else None for value in values)
        if admitted:
            result["history"] = tuple({"period": period, "values": {
                label: {"value": values[index], "unit": definitions[label]}
                for label, values in admitted.items()}} for index, period in enumerate(periods))
            result["provenance"] = dict(provenance)
            result["periodicity"] = trend.get("periodicity") or "UNAVAILABLE"
    result["missing"] = tuple(label for label in definitions if label not in admitted)
    return result


def build_valuation_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Explain admitted valuation evidence without deriving a multiple or target.

    Use individual fact provenance rather than the chart's shared timestamp:
    a retained close and a model estimate need not have the same evidence date.
    """
    facts = []
    models = []
    if page.get("status") == "AVAILABLE":
        for raw in page.get("fundamentals") or ():
            item = _mapping(raw)
            if (item.get("fact_name") in {"Last Certified Close", "ATLAS Fair Value"}
                    and item.get("classification") == "CERTIFIED_ATLAS"
                    and item.get("source") and item.get("evidence_ids")
                    and _finite(item.get("value"))):
                facts.append(dict(item))
        for raw in _mapping(page.get("financial_depth")).get("valuation_models") or ():
            item = _mapping(raw)
            if (_finite(item.get("value")) and item.get("unit") == "USD_PER_SHARE"
                    and item.get("source") == "CERTIFIED_ATLAS_VALUATION"):
                models.append({**dict(item), "assumptions": dict(_mapping(item.get("assumptions")))})
    return {"facts": tuple(facts), "models": tuple(models)}


def build_learning_guide(page: Mapping[str, Any]) -> dict[str, Any]:
    """Select evidence without calculating trends or treating missing data as zero."""
    if page.get("status") != "AVAILABLE":
        return {"status": "UNAVAILABLE", "earnings": (), "headlines": ()}
    snapshot = _mapping(page.get("financial_snapshot"))
    rows = []
    seen = set()
    for item in snapshot.get("items") or ():
        if snapshot.get("status") != "AVAILABLE" or not isinstance(item, Mapping):
            continue
        field = item.get("field")
        value = item.get("value")
        if field not in EARNINGS_FIELDS or field in seen or not item.get("evidence_id"):
            continue
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
            continue
        seen.add(field)
        title, explanation = EARNINGS_FIELDS[field]
        rows.append({**dict(item), "question": title, "explanation": explanation})
    changes = _mapping(page.get("recent_changes"))
    headlines = tuple(dict(item) for item in changes.get("items") or ()
                      if isinstance(item, Mapping) and item.get("headline")
                      and item.get("article_publisher") and item.get("article_timestamp")) if changes.get("status") == "AVAILABLE" else ()
    summary = _mapping(page.get("summary"))
    conditions = _mapping(summary.get("watch_conditions"))
    return {
        "status": "AVAILABLE", "earnings": tuple(rows), "headlines": headlines,
        "bull_watch": tuple(conditions.get("strengthen") or ()),
        "bear_watch": tuple(conditions.get("weaken") or ()),
        "risks": tuple(summary.get("risks") or ()),
        "snapshot": _mapping(page.get("evidence")).get("evaluation_snapshot_id"),
    }
