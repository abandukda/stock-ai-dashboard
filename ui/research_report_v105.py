"""
Atlas V105 — Institutional Research Report UI

This module renders the complete premium research report generated by
engines/research_engine_v105.py.
"""

from __future__ import annotations

from html import escape
from typing import Any, Mapping

import pandas as pd
import streamlit as st

from engines.research_engine_v105 import build_institutional_research


def _money(value: Any) -> str:
    try:
        return f"${float(value):,.2f}"
    except (TypeError, ValueError):
        return "Under review"


def _percent(value: Any, signed: bool = False) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "Under review"
    sign = "+" if signed and number > 0 else ""
    return f"{sign}{number:.1f}%"


def _score(value: Any) -> str:
    try:
        return f"{float(value):.1f}"
    except (TypeError, ValueError):
        return "Under review"


def _verdict(value: Any) -> str:
    return str(value or "MONITOR").replace("_", " ").title()


