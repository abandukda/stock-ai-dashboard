"""Evidence-only institutional Research V2 narrative projection.

This module is presentation-only.  It consumes the customer-safe Research V2
projection and never calls a provider, recalculates a certified decision, or
fills an unavailable field with an estimate.
"""
from __future__ import annotations

from typing import Any, Mapping
from services.research_analyst_readiness import analyst_display_fact


CONTRACT = "ATLAS_INSTITUTIONAL_RESEARCH_REPORT_V1"


def _map(value: Any) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _seq(value: Any) -> tuple[Any, ...]:
    return tuple(value) if isinstance(value, (list, tuple)) else ()


def _text(value: Any) -> str | None:
    text = str(value or "").strip()
    return text or None


def _condition(page: Mapping[str, Any], key: str) -> tuple[str, ...]:
    conditions = _map(_map(page.get("summary")).get("watch_conditions"))
    return tuple(str(item).strip() for item in _seq(conditions.get(key)) if str(item).strip())[:3]


def _metric_interpretations(page: Mapping[str, Any]) -> tuple[dict[str, Any], ...]:
    """Describe retained metrics and trend direction without deriving new facts."""
    trend = _map(page.get("financial_trend"))
    periods = _seq(trend.get("periods"))
    series = _map(trend.get("series")) if trend.get("status") == "AVAILABLE" else {}
    provenance = _map(trend.get("provenance"))
    evidence_ids = tuple(str(item) for item in _seq(provenance.get("evidence_ids")) if str(item).strip())
    meanings = {
        "Revenue": "Revenue is the money customers paid the company before expenses.",
        "EPS": "Earnings per share is profit allocated to each share.",
        "Operating Margin": "Operating margin shows how much operating profit remains from each dollar of sales.",
        "Gross Margin": "Gross margin shows what remains after the direct cost of the product or service.",
        "Net Margin": "Net margin shows how much bottom-line profit remains from each dollar of sales.",
        "Operating Cash Flow": "Operating cash flow shows cash generated by the core business.",
        "Free Cash Flow": "Free cash flow is cash left after operating needs and major investment spending.",
    }
    output: list[dict[str, Any]] = []
    for label, values in series.items():
        sequence = _seq(values)
        if not sequence or not evidence_ids:
            continue
        direction = "Trend unavailable"
        if len(sequence) >= 2:
            try:
                first, latest = float(sequence[-2]), float(sequence[-1])
                direction = "Improving" if latest > first else "Deteriorating" if latest < first else "Stable"
            except (TypeError, ValueError):
                direction = "Trend unavailable"
        output.append({
            "metric": str(label), "latest_value": sequence[-1],
            "latest_period": periods[-1] if periods else None,
            "direction": direction, "meaning": meanings.get(str(label), "This is a retained company financial measure."),
            "why_it_matters": (
                "The direction helps show whether the latest retained business result strengthened or weakened versus the preceding retained period."
                if direction != "Trend unavailable" else
                "A single retained observation cannot establish whether the business is improving or deteriorating."
            ),
            "evidence_ids": evidence_ids,
        })
    return tuple(output)


def build_institutional_research_report(page: Mapping[str, Any]) -> dict[str, Any]:
    """Build one five-minute stock dossier from an admitted customer projection."""
    if page.get("status") != "AVAILABLE":
        return {"contract": CONTRACT, "status": "UNAVAILABLE", "reason": "CUSTOMER_RESEARCH_NOT_PUBLISHED"}
    ticker = str(page.get("ticker") or "").strip().upper()
    identity = _map(page.get("identity"))
    evidence = _map(page.get("evidence"))
    if not ticker or str(identity.get("ticker") or "").strip().upper() != ticker:
        return {"contract": CONTRACT, "status": "UNAVAILABLE", "reason": "TICKER_IDENTITY_MISMATCH"}
    required = ("evaluation_snapshot_id", "candidate_digest", "publication_digest", "source_sha")
    if any(not evidence.get(key) for key in required):
        return {"contract": CONTRACT, "status": "UNAVAILABLE", "reason": "PUBLICATION_IDENTITY_INCOMPLETE"}

    about = _map(page.get("about")); profile = _map(about.get("profile"))
    company = str(page.get("company") or ticker)
    industry = _text(about.get("industry") or about.get("sector") or page.get("sector"))
    description = _text(profile.get("description") or profile.get("business_summary") or profile.get("company_description"))
    business = description or (
        f"{company} is classified in {industry}. A verified business description is unavailable."
        if industry else "A verified business description is unavailable in this evidence bundle."
    )
    summary = _map(page.get("summary")); header = _map(page.get("header"))
    thesis = tuple(str(item).strip() for item in _seq(summary.get("why_rating")) if str(item).strip())[:3]
    risks = tuple(str(item).strip() for item in _seq(summary.get("risks")) if str(item).strip())[:4]
    wall = _map(page.get("wall_street")); catalysts = _map(page.get("catalysts"))
    average_target = analyst_display_fact(page.get("analyst_context_readiness"), "average_target")
    recommendations = analyst_display_fact(page.get("analyst_context_readiness"), "recommendation_coverage")
    events = tuple(dict(item) for item in _seq(catalysts.get("events")) if isinstance(item, Mapping))[:3]
    strengthen, weaken, invalidate = (_condition(page, key) for key in ("strengthen", "weaken", "invalidate"))
    valuation = {
        "atlas_fair_value": header.get("fair_value"),
        "last_certified_close": header.get("price"),
        "fair_value_gap_pct": header.get("fair_value_gap_pct"),
        "as_of": header.get("price_timestamp"),
        "wall_street_status": wall.get("status") or "UNAVAILABLE",
        "wall_street_recommendations_status": recommendations["status"],
        "wall_street_target_average_status": average_target["status"],
        "wall_street_consensus": recommendations.get("consensus"),
        "wall_street_recommendation_period": recommendations.get("as_of"),
        "wall_street_target_average": average_target.get("value"),
        "wall_street_as_of": average_target.get("as_of"),
        "named_institution_opinions": (),
        "named_institution_limitation": "No verified licensed institution-specific opinions are retained for display.",
    }
    return {
        "contract": CONTRACT, "status": "AVAILABLE", "ticker": ticker, "company": company,
        "classification": "CONTEXTUAL_NON_SCORING", "external_model_active": False,
        "identity": {key: evidence.get(key) for key in required},
        "business": {"description": business, "industry": industry, "status": "AVAILABLE" if description else "LIMITED"},
        "investment_case": {"strengths": thesis, "risks": risks},
        "financial_story": {"status": "AVAILABLE" if _metric_interpretations(page) else "UNAVAILABLE",
                            "metrics": _metric_interpretations(page)},
        "valuation": valuation,
        "catalysts": {"status": "AVAILABLE" if events else "UNAVAILABLE", "events": events},
        "scenarios": {
            "bull": strengthen, "base": thesis[:2], "bear": weaken,
            "thesis_change": invalidate or weaken,
            "limitation": "Scenarios are conditional watchpoints, not forecasts or return estimates.",
        },
        "limitations": tuple(item for item in (
            None if description else "Verified business-description detail is unavailable.",
            None if risks else "No company-specific measured risk is retained; limited evidence does not mean no risk.",
            None if events else "No verified upcoming company event is retained.",
            None if wall.get("status") == "AVAILABLE" else "Wall Street context is unavailable or display-disabled.",
        ) if item),
    }


__all__ = ["CONTRACT", "build_institutional_research_report"]
